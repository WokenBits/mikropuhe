#!/usr/bin/env python3
"""Write port/src/tables.h: the text-stage data tables, read from PUHU.EXE's data segment.

    tools/gen_tables.py [original/files/PUHU.EXE] > port/src/tables.h

Offsets are in the program's data segment (DS = 0x194a; file offset = 0xa0a0 + offset).
"""
import os
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
b = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "original", "files", "PUHU.EXE"), "rb").read()
DS = 0xA0A0


def cstr(off):
    return b[DS + off:b.index(b"\0", DS + off)]


def lit(bs):
    out, prev_hex = "", False
    for c in bs:
        if 0x20 <= c < 0x7F and chr(c) not in '"\\' and not (prev_hex and chr(c) in "0123456789abcdefABCDEF"):
            out += chr(c)
            prev_hex = False
        else:
            out += "\\x%02x" % c
            prev_hex = True
    return out


words = cstr(0xD1B)
offs = struct.unpack_from("<7H", b, DS + 0x14CC)
thr = struct.unpack_from("<4H", b, DS + 0x14DA)
chunks, cur = [], b""
for w in words.split(b",")[:-1]:
    if len(cur) + len(w) + 1 > 90:
        chunks.append(cur)
        cur = b""
    cur += w + b","
chunks.append(cur)
L = ["/* Generated by tools/gen_tables.py from PUHU.EXE data (DS offsets in comments). Text is CP437. */",
     "/* DS:0x0d1b: number words, comma-terminated, %d entries */" % words.count(b","),
     "static const char NUM_WORDS[] =\n" + "\n".join('    "%s"' % lit(c) for c in chunks) + ";",
     "/* DS:0x14cc: first entry (0-based) of each of the seven inflected forms */",
     "static const uint16_t NUM_FORM_BASE[7] = {%s};" % ", ".join(map(str, offs)),
     "/* DS:0x14da: digits remaining after the group of biljoona, miljardi, miljoona, tuhat */",
     "static const uint16_t NUM_GROUP[4] = {%s};" % ", ".join(map(str, thr)),
     "/* DS:0x0ccc: the 32 characters that count as letters */",
     'static const uint8_t ALPHABET[33] = "%s";' % lit(b[DS + 0xCCC:DS + 0xCCC + 32]),
     "/* DS:0x0ced, DS:0x0cf2: upper-case letters outside A-Z and their lower-case forms */",
     'static const uint8_t UPPER_EXTRA[5] = "%s";' % lit(cstr(0xCED)),
     'static const uint8_t LOWER_EXTRA[5] = "%s";' % lit(cstr(0xCF2)),
     "/* DS:0x151b: characters of class 3 (specials that can be spoken or attach to a word) */"]
c3 = cstr(0x151B)
L.append('static const uint8_t CLASS3[%d] = "%s";' % (len(c3) + 1, lit(c3)))
L.append("/* DS:0x0cf7 and the pointer table at DS:0x0cff: letters rewritten before synthesis */")
rep = cstr(0xCF7)
ptrs = struct.unpack_from("<%dH" % (2 * len(rep)), b, DS + 0xCFF)[0::2]
L.append('static const uint8_t REWRITE_FROM[%d] = "%s";' % (len(rep) + 1, lit(rep)))
L.append("static const char *const REWRITE_TO[%d] = {%s};" % (len(rep), ", ".join('"%s"' % lit(cstr(p)) for p in ptrs)))
for name, off in (("STR_PUHELIN", 0x1552), ("STR_J_REWRITE", 0x155A), ("STR_DIGITS", 0x155E),
                  ("STR_MARKKAA", 0x1569), ("STR_PROSENTTIA", 0x1571), ("STR_ASTETTA", 0x157C),
                  ("STR_DOLLARIA", 0x1584), ("STR_PUNTAA", 0x158D), ("STR_PILKKU", 0x1594),
                  ("STR_NOLLA_PILKKU", 0x159E), ("STR_TOISTA", 0x15AD), ("STR_SENTENCE_END", 0x1CB)):
    L.append('static const char %s[] = "%s"; /* DS:0x%04x */' % (name, lit(cstr(off)), off))
print("\n".join(L))
