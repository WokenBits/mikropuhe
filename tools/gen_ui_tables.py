#!/usr/bin/env python3
"""Write port/src/ui_tables.h: the strings and tables of the full-screen interface, read from PUHU.EXE.

    tools/gen_ui_tables.py [original/files/PUHU.EXE] > port/src/ui_tables.h

Offsets are in the program's data segment (file offset = 0xa0a0 + offset). Text is CP437.
"""
import os
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
b = open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "original", "files", "PUHU.EXE"), "rb").read()
DS = 0xA0A0


def cstr(off):
    return b[DS + off:b.index(b"\0", DS + off)]


def lit(bs):
    out, prev_hex = "", False
    for c in bs:
        if 0x20 <= c < 0x7F and chr(c) not in '"\\?' and not (prev_hex and chr(c) in "0123456789abcdefABCDEF"):
            out += chr(c)
            prev_hex = False
        else:
            out += "\\x%02x" % c
            prev_hex = True
    return out


def wrapped(name, off):
    """A long string as several adjacent literals."""
    s, parts = cstr(off), []
    while s:
        cut = 80 if len(s) > 80 else len(s)
        parts.append(s[:cut])
        s = s[cut:]
    return "static const char %s[] = /* DS:0x%04x */\n%s;" % (name, off, "\n".join('    "%s"' % lit(p) for p in parts))


L = ["/* Generated by tools/gen_ui_tables.py from PUHU.EXE data (DS offsets in comments). Text is CP437. */"]
for name, off in (("UI_BAR_MAIN", 0x3AF), ("UI_BAR_SETTINGS", 0x356), ("UI_BANNER_FMT", 0x540),
                  ("UI_PROMPT", 0x7E8), ("UI_WELCOME", 0x7FF), ("UI_HELP_MAIN", 0x865),
                  ("UI_HELP_SETTINGS", 0x5B8), ("UI_SAVED", 0x688), ("UI_FIRST", 0x693), ("UI_LAST", 0x698),
                  ("UI_OK", 0x69E), ("UI_BYE", 0x57D), ("UI_ON", 0x590), ("UI_OFF", 0x593),
                  ("UI_C_AS_K", 0x5B1), ("UI_C_AS_S", 0x5B5), ("UI_PRESS_ENTER", 0x948),
                  ("UI_ERR_PROTECTED", 0x9A8), ("UI_ERR_MEMORY", 0x9D2), ("UI_ERR_NOT_FOUND", 0x9E1),
                  ("UI_WORD_DELIMITERS", 0x15EA)):
    L.append(wrapped(name, off))
L.append("/* DS:0x15d8: frame characters, single then double: top row, middle row, bottom row */")
L.append('static const unsigned char UI_FRAME[2][9] = {{%s}, {%s}};' % (
    ", ".join("0x%02x" % c for c in b[DS + 0x15D8:DS + 0x15E1]),
    ", ".join("0x%02x" % c for c in b[DS + 0x15E1:DS + 0x15EA])))
L.append("/* DS:0x0316: voice names as shown */")
L.append("static const char *const UI_VOICE_NAME[3] = {%s};" % ", ".join(
    '"%s"' % lit(cstr(struct.unpack_from("<H", b, DS + 0x316 + 4 * i)[0])) for i in range(3)))
L.append("/* DS:0x0292: the rows of the settings screen. type: 1 on/off, 2 number 0..8, 3 empty row, 4 the letter")
L.append(" * c as S or K, 5 the voice. word: which of the 14 setting words. spoken: the name read aloud, when it")
L.append(" * differs from the label. */")
L.append("static const struct { const char *label, *spoken; int type, word; } UI_ROWS[12] = {")
for i in range(12):
    r = b[DS + 0x292 + 11 * i:DS + 0x292 + 11 * i + 11]
    p1, _, p2, _ = struct.unpack_from("<HHHH", r, 0)
    L.append('    {"%s", %s, %d, %d},' % (lit(cstr(p1)) if p1 else "", '"%s"' % lit(cstr(p2)) if p2 else "NULL",
                                          r[8], struct.unpack_from("<H", r, 9)[0] // 2))
L.append("};")
# the serial number of this copy: stored inverted after the string at DS:0x096d (0x124ea)
nul = b.index(b"\0", DS + 0x96D)
L.append("/* 0x124ea: the serial number shown in the banner is the inverted 32-bit value after the string at")
L.append(" * DS:0x096d, so it belongs to this copy of PUHU.EXE */")
L.append("#define UI_SERIAL %dUL" % (struct.unpack_from("<I", b, nul + 1)[0] ^ 0xFFFFFFFF))
print("\n".join(L))
